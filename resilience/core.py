@dataclass(frozen=True)
class GoalPlan:
    target_buffer: float          # emergency-fund target in CAD
    current_buffer: float
    shortfall: float              # how much is missing (0 if already there)
    monthly_surplus: float        # I - S in normal times (can be <= 0)
    months_to_target: float | None  # None when the surplus can't close the gap
    target_kind: str = "months_of_S"


def goal_plan(row: pd.Series, target_months: float = 6.0, save_share: float = 1.0,
              target_kind: str = "months_of_S", shock: Shock = LAID_OFF_EI) -> GoalPlan:
    """Emergency-fund goal from the customer's own numbers.

    target_kind:
      "months_of_S"  target = target_months x S (the conventional benchmark)
      "ei_proof"     target = one-off + target_months x max(spending - income, 0) under `shock`.
                     "Already there" means exactly that the judges' (rounded) runway under
                     `shock` reaches target_months, so the goal never contradicts the verdict.
    save_share: share of the normal-times surplus (I - S) the customer commits.
    """
    if target_kind == "months_of_S":
        target = target_months * row["S"]
        shortfall = max(target - row["B"], 0.0)
    elif target_kind == "ei_proof":
        income, addons, one_off, base = shock_terms(row, shock)
        target = float(one_off + target_months * max(base + addons - income, 0.0))
        if apply_shock(row, shock).survives(target_months):
            shortfall = 0.0
        else:  # rounding can pass a buffer a hair under target; failing means something is missing
            shortfall = max(target - row["B"], 0.01)
    else:
        raise ValueError(f"unknown target_kind {target_kind!r}")
    surplus = row["I"] - row["S"]
    saving = save_share * surplus
    if shortfall == 0:
        months = 0.0
    elif saving > 0:
        months = math.ceil(shortfall / saving * 10) / 10  # round up: 0.0 only when already there
    else:
        months = None
    return GoalPlan(float(target), float(row["B"]), float(shortfall), float(surplus), months, target_kind)


@dataclass(frozen=True)
class BackupPlan:
    target_months: float
    shocked: RunwayResult
    monthly_cut_needed: float     # CAD per month of spending to cut (0 if already safe)
    flexible_pool: float          # non-fixed spending (card + cash) still left to cut
    cut_share_of_flexible: float | None
    feasible: bool                # cut fits inside the non-fixed pool
    after_cut: RunwayResult
    buffer_wiped: bool            # a one-off cost used up the whole buffer
    cash_needed: float            # when the buffer is wiped: cash (e.g. financing the
                                  # one-off) needed to get back to target_months after the cut
    normal_surplus: float         # I - S, to say how fast a wiped buffer rebuilds


def backup_plan(row: pd.Series, shock: Shock, target_months: float = 6.0) -> BackupPlan:
    """Monthly spending cut that brings runway back to >= target under the shock.

    The cut is sized on the unrounded runway, so it can exceed the strict minimum
    by a few dollars; it never falls short of the target.
    If a one-off cost wipes the buffer, the published formula gives 0 months
    whatever the spending, so the plan reports the cash needed instead.
    """
    shocked = apply_shock(row, shock)
    pool = float((1.0 - shock.flexible_cut_pct) * row["flexible_median"])
    surplus = float(row["I"] - row["S"])
    wiped = shocked.buffer_left <= 0
    cut = 0.0
    cash = 0.0
    if wiped:
        cut = min(max(shocked.gap, 0.0), pool)  # cut what the pool allows, then
        cash = -shocked.buffer_left + target_months * max(shocked.gap - cut, 0.0) + 0.01
        cash = math.ceil(cash * 100) / 100       # the rest has to come from cash or credit
    elif not shocked.survives(target_months):
        allowed_gap = shocked.buffer_left / target_months
        cut = math.ceil((shocked.gap - allowed_gap) * 100) / 100  # round up to the cent
    cut_share = (cut / pool) if pool > 0 else None
    feasible = (not wiped) and cut <= pool
    after = runway(shocked.buffer_left + shocked.one_off + cash, shocked.one_off,
                   shocked.spending_after - cut, shocked.income_after)
    return BackupPlan(target_months, shocked, cut, pool, cut_share, feasible, after,
                      wiped, cash, surplus)


@dataclass(frozen=True)
class Rung:
    step: str
    monthly_saving: float         # cumulative saving vs the shocked spending, CAD/month
    result: RunwayResult
    reaches_target: bool


@dataclass(frozen=True)
class Ladder:
    target_months: float
    shocked: RunwayResult
    already_safe: bool
    buffer_wiped: bool
    rungs: tuple[Rung, ...] = field(default_factory=tuple)
    first_sufficient: int | None = None   # index into rungs
    cash_or_credit_needed: float = 0.0    # if no rung reaches the target
    overdrawn: bool = False               # the buffer was negative before any shock

    @property
    def verdict(self) -> str:
        if self.already_safe:
            return "Survives without changes"
        if self.overdrawn:
            return "Already overdrawn: clear the debt with cash or credit first"
        if self.buffer_wiped:
            return "Buffer wiped by the one-off: needs cash or credit first"
        if self.first_sufficient is not None:
            return f"Reaches {self.target_months:g} months at: {self.rungs[self.first_sufficient].step}"
        return "Needs income or credit: spending cuts alone don't reach the target"


def backup_ladder(row: pd.Series, shock: Shock, target_months: float = 6.0) -> Ladder:
    """Minimum-pain ladder: stop at the first (cumulative) step that reaches the target.

    1 drop bank fees   2 non-fixed spending -10%   3 non-fixed -25%
    4 pause other (blank-purpose) standing orders, capped at the transfers seen in a typical month
    5 defer the running loan payment, capped at the loan payment seen in a typical month
    6 non-fixed -50%
    If none reaches it: income or credit needed (a line of credit arranged while employed).
    """
    shocked = apply_shock(row, shock)
    if shocked.survives(target_months):
        return Ladder(target_months, shocked, True, False)
    if shocked.buffer_left <= 0:
        cash = -shocked.buffer_left + target_months * max(shocked.gap, 0.0) + 0.01
        return Ladder(target_months, shocked, False, True, cash_or_credit_needed=math.ceil(cash * 100) / 100,
                      overdrawn=bool(row["B"] <= 0))

    fees = float(_get(row, "bank_fees_median"))
    nf = float((1.0 - shock.flexible_cut_pct) * _get(row, "flexible_median"))
    so = min(float(_get(row, "so_other")), float(_get(row, "transfers_out_other_median")))
    loan = min(float(_get(row, "P")), float(_get(row, "loan_payments_median")))
    steps = [
        ("Drop bank fees", fees),
        ("+ cut non-fixed spending 10%", fees + 0.10 * nf),
        ("+ cut non-fixed spending 25%", fees + 0.25 * nf),
        ("+ pause other standing orders", fees + 0.25 * nf + so),
        ("+ defer the running loan payment", fees + 0.25 * nf + so + loan),
        ("+ cut non-fixed spending 50%", fees + 0.50 * nf + so + loan),
    ]
    rungs, first, prev = [], None, 0.0
    for name, saving in steps:
        if saving <= prev:  # this account has nothing (more) to cut at this step
            continue
        prev = saving
        res = runway(shocked.buffer_left + shocked.one_off, shocked.one_off,
                     shocked.spending_after - saving, shocked.income_after)
        ok = res.survives(target_months)
        rungs.append(Rung(name, round(saving, 2), res, ok))
        if ok and first is None:
            first = len(rungs) - 1
    cash = 0.0
    if first is None:
        last_gap = shocked.gap - steps[-1][1]
        cash = max(target_months * max(last_gap, 0.0) - shocked.buffer_left, 0.0)
        cash = math.ceil(cash * 100) / 100
    return Ladder(target_months, shocked, False, False, tuple(rungs), first, cash)


