# Calibration of the judges' 6-month EI test against typical half-year spending (S6):
# share of accounts in each judge-runway band that fail 6 months on S6
# (research/ideation/income-volatility.md, verified by an independent script).
GREY_ZONE = ((6.0, 8.0, 0.819), (8.0, 10.0, 0.423), (10.0, 12.0, 0.231))


def goal_shock_for(shock: Shock) -> Shock:
    """The shock a job-loss-proof fund is sized on: the twist itself if it is a job loss, otherwise
    a job loss on EI 55% (or the twist's deeper income cut, so a 30% pay cut is covered too)."""
    if shock.is_job_loss:
        return shock
    return shock.with_(income_multiplier=min(shock.income_multiplier, 0.55), one_off_cost=0.0,
                       one_off_multiple_of_S=0.0, job_loss=True, name="Laid off: EI 55%")


def grey_zone_note(result: RunwayResult, shock: Shock | None = None) -> str | None:
    """Only for the judges' plain EI 55% job loss, the twist the calibration was measured on."""
    if shock is not None and shock.with_(name=LAID_OFF_EI.name) != LAID_OFF_EI:
        return None
    if result.no_shortfall or result.months is None:
        return None
    for lo, hi, share in GREY_ZONE:
        if lo <= result.months < hi:
            return (f"Grey zone: {share:.0%} of customers the formula puts at {lo:g}-{hi:g} months "
                    f"run out within 6 months on their own half-year spending.")
    return None


def loan_in_trouble(row) -> bool:
    """Loan status B (defaulted) or D (running, client in debt)."""
    return str(_get(row, "loan_status", "")) in DEFAULTED_LOAN_STATUSES


def credit_advice(row, amount: float, job_loss: bool = True) -> str:
    """What to say about a cash/credit hole, without pushing credit on a borrower in trouble."""
    amt = f"${amount:,.0f}"
    if loan_in_trouble(row):
        first = "start the EI claim on day one, " if job_loss else ""
        return (f"The remaining hole is {amt}. With a loan already in arrears or default, no new credit: "
                f"{first}ask for a hardship deferral on the loan, and run the spending steps.")
    return (f"Line up {amt} of credit before the shock: a Tangerine Line of Credit is easiest to arrange "
            "while still employed, subject to approval.")


def account_flags(row: pd.Series) -> list[tuple[str, str]]:
    """(code, plain-English note) for anything a judge or customer should know first."""
    f: list[tuple[str, str]] = []
    if row["B"] <= 0:
        f.append(("overdrawn", "Already overdrawn: the buffer is negative, so every runway is 0."))
    if row["I"] == 0:
        f.append(("no_income", "No typical income (median money in is $0): a job-loss shock changes nothing."))
    if row["S"] == 0:
        f.append(("no_spending", "No typical spending: shocks sized as 'months of spending' are $0."))
    if row["H"] == 0:
        if _get(row, "H_SO") > 0:
            f.append(("bills_by_standing_order",
                      f"Household bills paid by standing order (${_get(row, 'H_SO'):,.0f}/mo) are not in H, "
                      "so a bills shock adds $0 unless the bills fallback is on."))
        else:
            f.append(("no_bills", "No household bills recorded (H = 0): a bills shock adds $0."))
    last = _get(row, "last_month", DATA_END_MONTH)
    if isinstance(last, str) and last < DATA_END_MONTH:
        f.append(("stale", f"Account activity stops in {last}: the buffer may be out of date."))
    if _get(row, "months_of_data", 99) <= 13:
        f.append(("short_history", f"Only {int(_get(row, 'months_of_data'))} months of history."))
    age = _get(row, "owner_age", np.nan)
    if isinstance(age, (int, float)) and not np.isnan(age):
        if age < 18:
            f.append(("minor_owner", f"Owner is {age:.0f}: under 18."))
    if _get(row, "Pn") > 0:
        f.append(("pension", "Receives a pension: a job loss should not cut it (try the pension-aware view)."))
    if loan_in_trouble(row):
        f.append(("loan_trouble", f"Loan status {_get(row, 'loan_status', '')} (in arrears or defaulted): don't add new "
                  "credit; lead with an EI claim, a hardship deferral on the loan, and the spending steps."))
    if bool(_get(row, "pre_loan_negative", False)):
        f.append(("pre_loan_overdraft",
                  "Overdrawn before taking the loan: in this data every such borrower (27 of 27) defaulted."))
    elif bool(_get(row, "ever_negative", False)):
        f.append(("been_negative", "Has gone below zero before."))
    return f
