"""Deterministic resilience engine for the Tangerine "Resilience Rewired" track.

Every number here is computed from the track data with the judges' published
definitions (README of the Tangerine dataset). No LLM calls happen in this
module: any narrative layer must sit on top of these results.

Judges' definitions, from monthly_summary.csv, per account:
    I  typical monthly money in    = median(money_in)
    F  typical fixed costs         = median(household_bills + insurance + loan_payments)
    S  typical monthly spending    = median(money_out)
    B  buffer                      = mean(avg_daily_balance) over the last 6 rows by month
    H  household bills             = median(household_bills)
    P  loan payment                = loans.monthly_payment if the loan is still
                                     running at the end of 2025 (status C or D), else 0

Runway (months):
    buffer_left = B - one_off_costs
    gap         = spending_after_shock - income_after_shock
    buffer_left <= 0 -> 0
    gap <= 0         -> "no shortfall (120+)"
    else             -> min(buffer_left / gap, 120), rounded to 1 decimal

Reality checks (our own definitions, always shown NEXT TO the judges' number,
never instead of it): 2026 EI cap, EI waiting week, pension-aware job loss,
typical half-year spending (S6), a month-by-month path starting in January,
and a household-bills fallback for bills paid by standing order.
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
import pandas as pd

RUNWAY_CAP_MONTHS = 120.0
NO_SHORTFALL_LABEL = "no shortfall (120+)"
RUNNING_LOAN_STATUSES = ("C", "D")
DEFAULTED_LOAN_STATUSES = ("B", "D")
# Non-fixed spending: card + cash withdrawals. transfers_out_other is NOT here: in this
# data every unlabelled transfer out is generated by a standing order (a commitment),
# so it is a separate backup-plan rung ("pause other standing orders").
NONFIXED_COLUMNS = ("card_withdrawals", "cash_withdrawals_genuine")
FLEXIBLE_COLUMNS = NONFIXED_COLUMNS  # kept for backward compatibility
DATA_END_MONTH = "2025-12"
AGE_REFERENCE_DATE = "2025-12-31"

DATA_DIR = Path(__file__).resolve().parent.parent / "data"


# ---------------------------------------------------------------- loading

def load_monthly(data_dir: Path | str = DATA_DIR) -> pd.DataFrame:
    ms = pd.read_csv(Path(data_dir) / "monthly_summary.csv")
    return ms.sort_values(["account_id", "month"], kind="stable").reset_index(drop=True)


def load_loans(data_dir: Path | str = DATA_DIR) -> pd.DataFrame:
    return pd.read_csv(Path(data_dir) / "loans.csv")


# ------------------------------------------------------------- baseline

def baseline_metrics(monthly: pd.DataFrame, loans: pd.DataFrame) -> pd.DataFrame:
    """Per-account judges' numbers (I, F, S, B, H, P) plus monthly-only extras.

    `monthly` must hold every month row of each account; it is re-sorted by
    (account_id, month) here so "last 6 rows" is always by month.
    """
    ms = monthly.sort_values(["account_id", "month"], kind="stable").reset_index(drop=True)
    g = ms.groupby("account_id", sort=True)
    fixed = ms["household_bills"] + ms["insurance"] + ms["loan_payments"]

    out = pd.DataFrame({
        "I": g["money_in"].median(),
        "F": fixed.groupby(ms["account_id"]).median(),
        "S": g["money_out"].median(),
        "B": g.tail(6).groupby("account_id")["avg_daily_balance"].mean(),
        "H": g["household_bills"].median(),
    })
    running = loans[loans["status"].isin(RUNNING_LOAN_STATUSES)]
    out["P"] = running.set_index("account_id")["monthly_payment"].reindex(out.index).fillna(0.0)

    for col in (*NONFIXED_COLUMNS, "transfers_out_other", "bank_fees", "loan_payments", "insurance"):
        out[f"{col}_median"] = g[col].median()
    out["flexible_median"] = out[[f"{c}_median" for c in NONFIXED_COLUMNS]].sum(axis=1)
    out["Pn"] = g["pension_in"].median()
    out["pension_median"] = out["Pn"]
    out["months_of_data"] = g.size()
    out["first_month"] = g["month"].first()
    out["last_month"] = g["month"].last()
    out["ever_negative"] = g["days_below_zero"].sum() > 0

    # S6: typical half-year spending per month = median over sliding 6-month windows
    # of total money_out (opening month excluded, it starts mid-month), divided by 6.
    pos = g.cumcount()
    ms2 = ms[pos > 0]
    roll = ms2.groupby("account_id")["money_out"].rolling(6).sum().dropna()
    out["S6"] = (roll.groupby(level=0).median() / 6).reindex(out.index)

    # calendar-month spending profile (first and last month dropped as partial)
    inner = ms[(pos > 0) & (g.cumcount(ascending=False) > 0)]
    cal = inner.assign(cal=inner["month"].str[5:7].astype(int)).groupby(["account_id", "cal"])["money_out"].median()
    cal = cal.unstack().reindex(index=out.index, columns=range(1, 13))
    for m in range(1, 13):
        out[f"cal_{m:02d}"] = cal[m]
    out.index.name = "account_id"
    return out


def enrich_metrics(metrics: pd.DataFrame, monthly: pd.DataFrame, loans: pd.DataFrame,
                   standing_orders: pd.DataFrame, dispositions: pd.DataFrame,
                   clients: pd.DataFrame) -> pd.DataFrame:
    """Add standing-order, loan-history and owner fields used by flags and plans."""
    out = metrics.copy()
    ln = loans.set_index("account_id")
    out["loan_status"] = ln["status"].reindex(out.index)
    out["loan_start"] = ln["loan_start"].reindex(out.index)

    # overdrawn in any month strictly before the loan started
    l2 = loans[["account_id", "loan_start"]].assign(start_m=pd.to_datetime(loans["loan_start"]).dt.strftime("%Y-%m"))
    pre = monthly.merge(l2, on="account_id")
    pre = pre[pre["month"] < pre["start_m"]]
    out["pre_loan_negative"] = (pre.groupby("account_id")["days_below_zero"].sum() > 0).reindex(out.index).fillna(False)

    so = standing_orders
    out["H_SO"] = so[so["purpose"] == "household bills"].groupby("account_id")["amount"].sum().reindex(out.index).fillna(0.0)
    out["so_other"] = so[so["purpose"].isna()].groupby("account_id")["amount"].sum().reindex(out.index).fillna(0.0)

    own = dispositions[dispositions["type"] == "owner"].merge(clients, on="client_id")
    age = (pd.Timestamp(AGE_REFERENCE_DATE) - pd.to_datetime(own["birth_date"])).dt.days / 365.25
    out["owner_age"] = pd.Series(age.values, index=own["account_id"]).groupby(level=0).first().reindex(out.index)
    out["owner_gender"] = own.set_index("account_id")["gender"].groupby(level=0).first().reindex(out.index)
    return out


def build_metrics(data_dir: Path | str = DATA_DIR) -> pd.DataFrame:
    """Everything the engine and app need, one row per account_id."""
    d = Path(data_dir)
    ms = load_monthly(d)
    loans = load_loans(d)
    m = baseline_metrics(ms, loans)
    return enrich_metrics(m, ms, loans, pd.read_csv(d / "standing_orders.csv"),
                          pd.read_csv(d / "dispositions.csv"), pd.read_csv(d / "clients.csv"))


# ---------------------------------------------------------------- shocks

@dataclass(frozen=True)
class Shock:
    """A scenario applied to one account's typical month.

    Judges' levers:
    income_multiplier   share of I still coming in (0.55 = EI at 55%).
    bills_increase_pct  household bills rise by this share of H (0.15 = +15%).
    extra_monthly_cost  any other new monthly cost, in CAD.
    one_off_cost        a one-time cost taken from the buffer, in CAD.
    one_off_multiple_of_S  a one-time cost as a multiple of S (1.0 = "a full month").
    flexible_cut_pct    share of non-fixed spending (card + cash) the customer cuts.

    Reality checks (off by default, so the defaults reproduce the judges' answers):
    income_cap_monthly  ceiling on the EI part of income (2026: EI_2026_MAX_MONTHLY).
    waiting_week        EI pays nothing for the first week: one week of EI becomes a one-off.
    pension_aware       a job loss does not cut pension income (Pn is kept in full).
    spending_basis      "S" (judges: median month) or "S6" (typical half-year per month).
    bills_fallback      use max(H, household-bills standing orders) when H misses them.
    job_loss            True when the income drop is a layoff on EI (enables the EI cap, waiting
                        week and pension checks). A pay cut or reduced hours is NOT a job loss.
    """

    income_multiplier: float = 1.0
    income_cap_monthly: float | None = None
    bills_increase_pct: float = 0.0
    extra_monthly_cost: float = 0.0
    one_off_cost: float = 0.0
    one_off_multiple_of_S: float = 0.0
    flexible_cut_pct: float = 0.0
    waiting_week: bool = False
    pension_aware: bool = False
    spending_basis: str = "S"
    bills_fallback: bool = False
    job_loss: bool = False
    name: str = "custom"

    def with_(self, **changes) -> "Shock":
        d = {**self.__dict__, **changes}
        return Shock(**d)

    @property
    def is_job_loss(self) -> bool:
        return self.job_loss and self.income_multiplier < 1.0


# Canadian reality check (opt-in; the judges' formula has no cap).
# "This means that you can receive a maximum amount of $729 per week." and
# "As of January 1, 2026, the maximum yearly insurable earnings amount is $68,900."
# Source: https://www.canada.ca/en/services/benefits/ei/ei-regular-benefit/benefit-amount.html
# EI benefits are taxable, so this is a gross amount.
EI_2026_MAX_WEEKLY = 729.0
EI_2026_MAX_MONTHLY = EI_2026_MAX_WEEKLY * 52 / 12  # 3,159.00
WEEKS_PER_MONTH = 52 / 12

BASELINE = Shock(name="Baseline (no shock)")
LAID_OFF_EI = Shock(income_multiplier=0.55, job_loss=True, name="Laid off: EI at 55% of usual income")
LAID_OFF_EI_CAPPED = Shock(income_multiplier=0.55, income_cap_monthly=EI_2026_MAX_MONTHLY, job_loss=True,
                           name="Laid off: EI at 55%, capped at the 2026 maximum ($729/week)")
FURNACE = Shock(one_off_multiple_of_S=1.0, name="Furnace dies: repair = 1 month of typical spending")
DOUBLE_WHAMMY = Shock(income_multiplier=0.55, bills_increase_pct=0.15, job_loss=True,
                      name="Job loss (EI 55%) + household bills +15%")
README_TWISTS = (LAID_OFF_EI, FURNACE, DOUBLE_WHAMMY)


@dataclass(frozen=True)
class RunwayResult:
    months: float | None          # None when there is no shortfall
    no_shortfall: bool
    buffer_left: float
    gap: float
    income_after: float
    spending_after: float
    one_off: float

    @property
    def capped(self) -> bool:
        return not self.no_shortfall and self.months is not None and self.months >= RUNWAY_CAP_MONTHS

    @property
    def label(self) -> str:
        if self.no_shortfall:
            return NO_SHORTFALL_LABEL
        return f"{self.months:.1f} (cap)" if self.capped else f"{self.months:.1f}"

    def survives(self, months: float) -> bool:
        return self.no_shortfall or (self.months is not None and self.months >= months)


def runway(buffer: float, one_off: float, spending_after: float, income_after: float) -> RunwayResult:
    """The judges' runway formula, exactly as published."""
    buffer_left = buffer - one_off
    gap = spending_after - income_after
    if buffer_left <= 0:
        return RunwayResult(0.0, False, buffer_left, gap, income_after, spending_after, one_off)
    if gap <= 0:
        return RunwayResult(None, True, buffer_left, gap, income_after, spending_after, one_off)
    months = float(np.round(min(buffer_left / gap, RUNWAY_CAP_MONTHS), 1))  # same rounding as portfolio_runway
    return RunwayResult(months, False, buffer_left, gap, income_after, spending_after, one_off)


def _get(x, name: str, default: float = 0.0):
    """Column of a DataFrame or field of a row; missing/NaN -> default (scalar rows only)."""
    if isinstance(x, pd.DataFrame):
        return x[name] if name in x.columns else pd.Series(default, index=x.index, dtype=float)
    v = x.get(name, default)
    try:
        return default if v is None or math.isnan(v) else v
    except TypeError:
        return v


def shock_terms(x, shock: Shock):
    """(income_after, monthly spending add-ons, one_off, base spending) for a row or a frame.

    Spending after the shock = base spending + add-ons. Base is S, or S6 when
    spending_basis == "S6". Works on a single account row or the whole metrics frame.
    """
    I, S, H = _get(x, "I"), _get(x, "S"), _get(x, "H")
    if shock.pension_aware:
        Pn = _get(x, "Pn")
        pension = np.minimum(Pn, I)
        earned = I - pension
    else:
        pension, earned = 0.0, I
    ei = shock.income_multiplier * earned
    if shock.income_cap_monthly is not None:
        ei = np.minimum(ei, shock.income_cap_monthly)
    income = ei + pension

    H_eff = np.maximum(H, _get(x, "H_SO")) if shock.bills_fallback else H
    addons = shock.bills_increase_pct * H_eff + shock.extra_monthly_cost \
        - shock.flexible_cut_pct * _get(x, "flexible_median")

    if shock.spending_basis == "S6":
        s6 = _get(x, "S6", np.nan)
        base = s6.fillna(S) if isinstance(s6, pd.Series) else (S if s6 is None or np.isnan(s6) else s6)
    elif shock.spending_basis == "S":
        base = S
    else:
        raise ValueError(f"unknown spending_basis {shock.spending_basis!r}")

    one_off = shock.one_off_cost + shock.one_off_multiple_of_S * S
    if shock.waiting_week and shock.is_job_loss:
        one_off = one_off + ei / WEEKS_PER_MONTH  # one week of EI not paid
    return income, addons, one_off, base


def apply_shock(row: pd.Series, shock: Shock) -> RunwayResult:
    """Runway for one account (a row of the metrics table) under a shock."""
    income, addons, one_off, base = shock_terms(row, shock)
    return runway(float(row["B"]), float(one_off), float(base + addons), float(income))


def portfolio_runway(metrics: pd.DataFrame, shock: Shock) -> pd.Series:
    """Vectorised runway for every account. no-shortfall is encoded as +inf."""
    income, addons, one_off, base = shock_terms(metrics, shock)
    buffer_left = metrics["B"] - one_off
    gap = base + addons - income
    with np.errstate(divide="ignore", invalid="ignore"):
        finite = np.round(np.minimum(buffer_left / gap, RUNWAY_CAP_MONTHS), 1)
    out = np.where(buffer_left <= 0, 0.0, np.where(gap <= 0, np.inf, finite))
    return pd.Series(out, index=metrics.index, name=shock.name)


# ------------------------------------------------- month-by-month reality path

def _calendar_matrix(x) -> np.ndarray:
    cols = [f"cal_{m:02d}" for m in range(1, 13)]
    if isinstance(x, pd.DataFrame):
        cal = x.reindex(columns=cols)
        return cal.apply(lambda c: c.fillna(x["S"])).to_numpy(float)
    return np.array([[_get(x, c, float(x["S"])) for c in cols]], float)


def portfolio_calendar_path(metrics: pd.DataFrame, shock: Shock, start_month: int = 1,
                            horizon: int = 120) -> pd.Series:
    """Runway when each month costs that account's median spending for that calendar month.

    The shock hits at the start of `start_month` (1 = January, the costliest month in this
    data). Income is the post-shock income every month; one-offs come off the buffer first.
    Returns months until the balance goes negative (1 decimal), 0 if the buffer is already
    gone, +inf if it never runs out within `horizon` months.
    """
    income, addons, one_off, _ = shock_terms(metrics, shock)
    inc = np.asarray(income, float) * np.ones(len(metrics))
    add = np.asarray(addons, float) * np.ones(len(metrics))
    cal = _calendar_matrix(metrics)
    bal = metrics["B"].to_numpy(float) - np.asarray(one_off, float) * np.ones(len(metrics))
    out = np.full(len(metrics), np.inf)
    out[bal <= 0] = 0.0
    alive = bal > 0
    for k in range(horizon):
        spend = cal[:, (start_month - 1 + k) % 12] + add
        net = inc - spend
        dies = alive & (bal + net < 0)
        out[dies] = np.round(k + bal[dies] / (spend[dies] - inc[dies]), 1)
        alive &= ~dies
        bal = np.where(alive, bal + net, bal)
    return pd.Series(out, index=metrics.index, name=f"{shock.name} (calendar path from month {start_month})")


def calendar_path(row: pd.Series, shock: Shock, start_month: int = 1) -> float:
    """Single-account version of portfolio_calendar_path."""
    needed = ("I", "S", "B", "H", "Pn", "H_SO", "flexible_median", "S6", *[f"cal_{m:02d}" for m in range(1, 13)])
    frame = pd.DataFrame([{c: float(row[c]) for c in needed if c in row.index}])
    return float(portfolio_calendar_path(frame, shock, start_month).iloc[0])


